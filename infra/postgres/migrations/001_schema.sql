-- --------------------------------------------------------
-- Table: activation_tokens (chỉ lưu sha256 của mã — NFR-S2; bản rõ trả đúng 1 lần lúc tạo)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS activation_tokens (
  id              BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  home_id         INT         NOT NULL,
  code_hash       CHAR(64)    NOT NULL,
  token_type      VARCHAR(32) NOT NULL DEFAULT 'INITIAL_CLAIM',
  expires_at      TIMESTAMPTZ NOT NULL,
  used_at         TIMESTAMPTZ NULL,
  used_by_user_id INT         NULL,
  revoked_at      TIMESTAMPTZ NULL,
  revoked_by      INT         NULL,
  created_by      INT         NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT uq_activation_tokens_code_hash UNIQUE (code_hash),
  CONSTRAINT ck_activation_tokens_token_type CHECK (token_type IN ('INITIAL_CLAIM')),
  CONSTRAINT fk_activation_tokens_home       FOREIGN KEY (home_id)         REFERENCES smart_homes (id) ON DELETE CASCADE,
  CONSTRAINT fk_activation_tokens_used_by    FOREIGN KEY (used_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_activation_tokens_revoked_by FOREIGN KEY (revoked_by)      REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_activation_tokens_created_by FOREIGN KEY (created_by)      REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_activation_tokens_home ON activation_tokens (home_id);
CREATE INDEX IF NOT EXISTS idx_activation_tokens_used_by    ON activation_tokens (used_by_user_id);
CREATE INDEX IF NOT EXISTS idx_activation_tokens_revoked_by ON activation_tokens (revoked_by);
CREATE INDEX IF NOT EXISTS idx_activation_tokens_created_by ON activation_tokens (created_by);


-- --------------------------------------------------------
-- Table: audit_log (kho của Log Center — FR-10.4)
-- Không FK home_id/actor_user_id: dòng log phải sống sau khi xoá nhà/người dùng.
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  event_type   VARCHAR(64)  NOT NULL,
  category     VARCHAR(16)  NOT NULL DEFAULT 'security',
  severity     VARCHAR(16)  NOT NULL DEFAULT 'info',
  device_id    INT          NULL,
  home_id      INT          NULL,
  actor_user_id INT         NULL,
  message      VARCHAR(255) NULL,
  ip_address   VARCHAR(45)  NULL,
  user_agent   VARCHAR(512) NULL,
  details      JSONB        NULL,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT ck_audit_log_category CHECK (category IN ('gateway','device','provision','mqtt','security','auth','activity','automation','ota','error')),
  CONSTRAINT ck_audit_log_severity CHECK (severity IN ('critical','warning','info','success')),
  CONSTRAINT fk_audit_log_device FOREIGN KEY (device_id) REFERENCES devices (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_log_event_created    ON audit_log (event_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_log_category_created ON audit_log (category, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_log_home_created     ON audit_log (home_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_log_device           ON audit_log (device_id);

-- --------------------------------------------------------
-- Table: notifications
-- Nhân viên: target_role = admin|operator|all (cờ is_read dùng chung).
-- Khách hàng: target_role = 'user', user_id = người nhận (mỗi người một dòng).
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS notifications (
  id           INT          GENERATED BY DEFAULT AS IDENTITY,
  title        VARCHAR(255) NOT NULL,
  message      TEXT         NOT NULL,
  type         VARCHAR(64)  NOT NULL DEFAULT 'info',
  severity     VARCHAR(16)  NOT NULL DEFAULT 'info',
  actor_id     INT          NULL,
  actor_username VARCHAR(64) NULL,
  actor_role   VARCHAR(32)  NULL,
  target_role  VARCHAR(32)  NOT NULL DEFAULT 'admin',
  related_device_id INT     NULL DEFAULT NULL,
  user_id      INT          NULL,
  home_id      INT          NULL,
  is_read      BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT ck_notifications_severity CHECK (severity IN ('critical','warning','info','success')),
  CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_notifications_home FOREIGN KEY (home_id) REFERENCES smart_homes (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_target_is_read        ON notifications (target_role, is_read);
CREATE INDEX IF NOT EXISTS idx_created_at            ON notifications (created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_user    ON notifications (user_id, is_read, created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_home    ON notifications (home_id);

-- --------------------------------------------------------
-- Table: smart_home_members
-- Lời mời đang chờ: user_id NULL + invite_email NOT NULL.
-- Thành viên hiệu lực: user_id NOT NULL AND (expires_at IS NULL OR expires_at > NOW()).
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS smart_home_members (
  id                INT          GENERATED BY DEFAULT AS IDENTITY,
  home_id           INT          NOT NULL,
  user_id           INT          NULL,
  member_role       VARCHAR(16)  NOT NULL,
  display_name      VARCHAR(128) NULL,
  invite_email      VARCHAR(190) NULL,
  invite_expires_at TIMESTAMPTZ  NULL,
  invited_by        INT          NULL,
  expires_at        TIMESTAMPTZ  NULL,
  accepted_at       TIMESTAMPTZ  NULL,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT uq_smart_home_members_home_user UNIQUE (home_id, user_id),
  CONSTRAINT ck_smart_home_members_member_role CHECK (member_role IN ('OWNER','CONTROLLER','VIEWER','GUEST')),
  CONSTRAINT fk_smart_home_members_home       FOREIGN KEY (home_id)    REFERENCES smart_homes (id) ON DELETE CASCADE,
  CONSTRAINT fk_smart_home_members_user       FOREIGN KEY (user_id)    REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_smart_home_members_invited_by FOREIGN KEY (invited_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_smart_home_members_user   ON smart_home_members (user_id);
CREATE INDEX IF NOT EXISTS idx_smart_home_members_invite ON smart_home_members (invite_email);
CREATE INDEX IF NOT EXISTS idx_smart_home_members_invited_by ON smart_home_members (invited_by);

-- --------------------------------------------------------
-- Table: member_device_access (thiết bị GUEST được phép dùng — FR-6.3)

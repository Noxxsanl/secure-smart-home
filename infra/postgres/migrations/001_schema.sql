-- ============================================================
-- Secure Smart Home IoT – Database Schema (PostgreSQL 16)
-- Migration: 001_schema.sql
--
-- Đây là BASELINE duy nhất của schema V2 cho PostgreSQL. Chạy khi volume PostgreSQL Docker còn
-- trống (infra/postgres/init/00_init.sh gọi file này bằng role ứng dụng, nên bảng thuộc role đó) hoặc chạy
-- tay theo docs/guides/CHAY_LOCAL.md:
--   psql -v ON_ERROR_STOP=1 -U <app_user> -d secure_smart_home_iot -f infra/postgres/migrations/001_schema.sql
-- File idempotent (IF NOT EXISTS, ON CONFLICT DO NOTHING) nên chạy lại không hỏng dữ liệu.
--
-- Thay đổi schema SAU baseline này KHÔNG sửa vào đây mà thêm vào cuối mảng "migrations" trong
-- backend/src/infrastructure/database/migrate.ts (chạy mỗi lần backend khởi động, theo dõi bằng bảng _migrations).
-- Khi đó cập nhật file này song song để DB tạo mới cũng có schema cuối cùng — migration runtime
-- gặp đối tượng đã tồn tại sẽ được ghi nhận là đã áp dụng, nên hai nguồn phải luôn khớp nhau.
-- Tên bảng/cột theo docs/architecture/DATABASE_REFACTOR_SMARTHOME.md §6–7 và CONTRACT_V2 §1.
--
-- Quy ước PostgreSQL của dự án:
--   * id: INT GENERATED BY DEFAULT AS IDENTITY (BIGINT cho log/telemetry) — BY DEFAULT để seed chèn
--     được id tường minh; không dùng kiểu số không dấu.
--   * Cờ 0/1 là BOOLEAN; thời gian là TIMESTAMPTZ (lưu tuyệt đối, backend ép session UTC); JSON là JSONB.
--   * ENUM của MySQL → VARCHAR + CHECK đặt tên ck_<bảng>_<cột> (thêm giá trị mới = đổi CHECK bằng migration).
--   * Bảng có updated_at tự cập nhật qua trigger dùng chung set_updated_at() (thay cơ chế tự cập nhật theo cột của MySQL).
--   * users.username/email so khớp KHÔNG phân biệt hoa thường nhờ unique index theo LOWER(...);
--     truy vấn đăng nhập phải so sánh LOWER(col) = LOWER($1) để dùng được index này.
-- ============================================================

-- unaccent: tìm kiếm Dashboard không phân biệt dấu tiếng Việt (collation MySQL cũ bỏ qua dấu, ILIKE thì
-- không) — SQL dùng `unaccent(col) ILIKE unaccent(?)`. Extension "trusted" từ PostgreSQL 13 nên role
-- owner của database tạo được, không cần superuser.
CREATE EXTENSION IF NOT EXISTS unaccent;

-- Trigger dùng chung: gán updated_at = thời điểm UPDATE (smart_homes, rooms, devices, automation_rules).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

-- --------------------------------------------------------
-- Table: users
-- Nhân viên (admin/operator) có username; khách hàng (user) đăng nhập bằng email nên username NULL.
-- username/email là unique index theo LOWER() (không dùng citext) — nhiều NULL vẫn hợp lệ.
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            INT           GENERATED BY DEFAULT AS IDENTITY,
  username      VARCHAR(64)   NULL,
  email         VARCHAR(190)  NULL,
  full_name     VARCHAR(128)  NULL,
  password_hash VARCHAR(255)  NOT NULL,
  role          VARCHAR(16)   NOT NULL DEFAULT 'operator',
  status        VARCHAR(16)   NOT NULL DEFAULT 'active',
  created_at    TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  last_login    TIMESTAMPTZ   NULL,
  -- Thu hồi phiên JWT stateless: token mang claim tv, lệch cột này (đổi mật khẩu/khoá/đăng xuất) → 401.
  token_version INT           NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  CONSTRAINT ck_users_role   CHECK (role IN ('admin','operator','user')),
  CONSTRAINT ck_users_status CHECK (status IN ('active','locked')),
  CONSTRAINT ck_users_token_version CHECK (token_version >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email    ON users (LOWER(email));

-- --------------------------------------------------------
-- Table: customers (hồ sơ khách hàng, 1-1 với users.role='user')
-- user_tag: "<slug>#<4 số>", ví dụ dat#4821 — dùng để Operator gán chủ nhà.
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS customers (
  id           INT           GENERATED BY DEFAULT AS IDENTITY,
  user_id      INT           NOT NULL,
  full_name    VARCHAR(128)  NOT NULL,
  phone        VARCHAR(20)   NULL,
  address      VARCHAR(255)  NULL,
  user_tag     VARCHAR(32)   NOT NULL,
  created_at   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT uq_customers_user_id  UNIQUE (user_id),
  CONSTRAINT uq_customers_user_tag UNIQUE (user_tag),
  CONSTRAINT fk_customers_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- --------------------------------------------------------
-- Table: smart_homes
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS smart_homes (
  id                  INT          GENERATED BY DEFAULT AS IDENTITY,
  name                VARCHAR(128) NOT NULL,
  package_code        VARCHAR(16)  NOT NULL,
  address             VARCHAR(255) NULL,
  expected_owner_name VARCHAR(128) NULL,
  timezone            VARCHAR(64)  NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
  status              VARCHAR(16)  NOT NULL DEFAULT 'unclaimed',
  owner_user_id       INT          NULL,
  created_by          INT          NULL,
  claimed_at          TIMESTAMPTZ  NULL,
  created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT ck_smart_homes_package_code CHECK (package_code IN ('KIT_A','KIT_B')),
  CONSTRAINT ck_smart_homes_status       CHECK (status IN ('unclaimed','active','suspended')),
  CONSTRAINT fk_smart_homes_owner      FOREIGN KEY (owner_user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_smart_homes_created_by FOREIGN KEY (created_by)    REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_smart_homes_status ON smart_homes (status);
CREATE INDEX IF NOT EXISTS idx_smart_homes_owner  ON smart_homes (owner_user_id);
-- Index cho cột FK: InnoDB tự tạo, PostgreSQL thì không — thiếu thì xoá/sửa dòng cha quét toàn bảng con.
CREATE INDEX IF NOT EXISTS idx_smart_homes_created_by ON smart_homes (created_by);
CREATE OR REPLACE TRIGGER trg_smart_homes_updated_at
  BEFORE UPDATE ON smart_homes FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- --------------------------------------------------------
-- Table: rooms
-- room_type: living_room|bedroom|kitchen|bathroom|office|garage|garden|door (kiểm ở tầng ứng dụng)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS rooms (
  id           INT          GENERATED BY DEFAULT AS IDENTITY,
  home_id      INT          NOT NULL,
  name         VARCHAR(64)  NOT NULL,
  room_type    VARCHAR(32)  NOT NULL,
  sort_order   SMALLINT     NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT fk_rooms_home FOREIGN KEY (home_id) REFERENCES smart_homes (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_rooms_home ON rooms (home_id);
CREATE OR REPLACE TRIGGER trg_rooms_updated_at
  BEFORE UPDATE ON rooms FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- --------------------------------------------------------
-- Table: devices
-- 1 dòng = 1 thiết bị logic. device_type giữ 'sensor'|'gateway' (danh tính cho HMAC);
-- loại chức năng nằm ở cột category. Dòng node trỏ về dòng gateway qua gateway_device_id.
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS devices (
  id           INT          GENERATED BY DEFAULT AS IDENTITY,
  device_id    VARCHAR(64)  NOT NULL,
  device_name  VARCHAR(128) NOT NULL,
  device_type  VARCHAR(16)  NOT NULL,
  secret_key   VARCHAR(64)  NOT NULL,
  status       VARCHAR(16)  NOT NULL DEFAULT 'inactive',
  location     VARCHAR(255) NULL,
  fail_count   SMALLINT     NOT NULL DEFAULT 0,
  last_seen    TIMESTAMPTZ  NULL,
  last_ip      VARCHAR(45)  NULL,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  created_by   INT          NULL,
  home_id      INT          NULL,
  room_id      INT          NULL,
  gateway_device_id INT     NULL,
  node_uid     VARCHAR(64)  NULL,
  category     VARCHAR(16)  NOT NULL DEFAULT 'sensor',
  power_state  BOOLEAN      NULL,
  firmware_version VARCHAR(32) NULL,
  rssi         SMALLINT     NULL,
  wifi_ssid    VARCHAR(64)  NULL,
  provision_status VARCHAR(16) NOT NULL DEFAULT 'pending',
  is_simulated BOOLEAN      NOT NULL DEFAULT FALSE,
  sim_online   BOOLEAN      NOT NULL DEFAULT TRUE,
  updated_at   TIMESTAMPTZ  NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_devices_device_id UNIQUE (device_id),
  CONSTRAINT ck_devices_device_type      CHECK (device_type IN ('sensor','gateway')),
  CONSTRAINT ck_devices_status           CHECK (status IN ('inactive','active','blocked')),
  CONSTRAINT ck_devices_category         CHECK (category IN ('gateway','sensor','relay','camera','door_contact')),
  CONSTRAINT ck_devices_provision_status CHECK (provision_status IN ('pending','provisioned')),
  CONSTRAINT ck_devices_fail_count       CHECK (fail_count >= 0),
  CONSTRAINT fk_devices_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_devices_home    FOREIGN KEY (home_id) REFERENCES smart_homes (id) ON DELETE SET NULL,
  CONSTRAINT fk_devices_room    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE SET NULL,
  CONSTRAINT fk_devices_gateway FOREIGN KEY (gateway_device_id) REFERENCES devices (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_devices_status    ON devices (status);
CREATE INDEX IF NOT EXISTS idx_devices_home_room ON devices (home_id, room_id);
CREATE INDEX IF NOT EXISTS idx_devices_gateway   ON devices (gateway_device_id);
CREATE INDEX IF NOT EXISTS idx_devices_category  ON devices (category);
CREATE INDEX IF NOT EXISTS idx_devices_room       ON devices (room_id);
CREATE INDEX IF NOT EXISTS idx_devices_created_by ON devices (created_by);
-- Khác MySQL (chỉ đổi khi giá trị thật sự khác), trigger này gán updated_at ở mọi UPDATE.
CREATE OR REPLACE TRIGGER trg_devices_updated_at
  BEFORE UPDATE ON devices FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- --------------------------------------------------------
-- Table: sensor_data
-- Giữ theo THỜI GIAN (mặc định 8 ngày, job retention hằng giờ) để vẽ được biểu đồ 7 ngày.
-- idx_sensor_data_received phục vụ DELETE ... WHERE received_at < $1 của job dọn dẹp.
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS sensor_data (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  device_id    INT          NOT NULL,
  gateway_id   INT          NOT NULL,
  payload      JSONB        NOT NULL,
  received_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT fk_sensor_data_device  FOREIGN KEY (device_id)  REFERENCES devices (id) ON DELETE CASCADE,
  CONSTRAINT fk_sensor_data_gateway FOREIGN KEY (gateway_id) REFERENCES devices (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_sensor_data_device_received ON sensor_data (device_id, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_sensor_data_received        ON sensor_data (received_at);
CREATE INDEX IF NOT EXISTS idx_sensor_data_gateway         ON sensor_data (gateway_id);

